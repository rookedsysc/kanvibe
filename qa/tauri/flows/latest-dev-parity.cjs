const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const https = require('node:https');
const { execFileSync } = require('node:child_process');
const { launchKanVibeTauri } = require('../lib/launchTauri.cjs');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));

async function main() {
  const out = path.resolve(process.argv[2] || `qa-results/latest-${Date.now()}`);
  if (fs.existsSync(path.join(out, 'app-data'))) throw new Error('Use a fresh QA directory');
  fs.mkdirSync(out, { recursive: true });
  const repo = path.join(out, `repository-${Date.now()}`); fs.mkdirSync(repo);
  const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' });
  git('init', '-b', 'main'); git('config', 'user.name', 'QA'); git('config', 'user.email', 'qa@kanvibe.local');
  fs.writeFileSync(path.join(repo, 'README.md'), '# Latest dev QA\n');git('add', '.');git('commit', '-m', 'Fixture');
  const appDataDir = path.join(out, 'app-data');
  let { app, page } = await launchKanVibeTauri({ appDataDir, hookPort: 19752 });
  const checks = [], sockets = [], created = [];
  const invoke = (ns, method, ...args) => page.evaluate(({ ns, method, args }) => window.kanvibeDesktop.invoke(ns, method, args), { ns, method, args });
  const record = name => { checks.push({ name, ok: true }); console.log(`PASS ${name}`); };
  const request = async (method, route, body, headers = {}) => {
    const response = await fetch(`http://127.0.0.1:19752${route}`, { method, headers: { 'content-type': 'application/json', ...headers }, ...(body === undefined ? {} : { body: JSON.stringify(body) }), signal: AbortSignal.timeout(60000) });
    return { status: response.status, body: await response.json() };
  };
  const tlsRequest = (method = 'GET', route = '/api/mobile/board', body, headers = {}) => new Promise((resolve, reject) => {
    const req = https.request(`https://127.0.0.1:19762${route}`, { method, rejectUnauthorized: false, agent: false, headers: { 'content-type': 'application/json', ...headers } }, response => {
      const fingerprint = response.socket.getPeerCertificate().fingerprint256.replaceAll(':', '').toLowerCase();
      let text = ''; response.on('data', chunk => { text += chunk; });response.on('end', () => resolve({ status: response.statusCode, fingerprint, body: JSON.parse(text) }));
    }); req.on('error', reject);req.setTimeout(10000, () => req.destroy(new Error('TLS timeout')));
    req.end(body === undefined ? undefined : JSON.stringify(body));
  });
  try {
    await invoke('appSettings', 'setBackgroundSyncEnabled', false);
    await invoke('appSettings', 'setDefaultSessionType', 'terminal');
    assert.equal((await request('GET', '/api/hooks/health', undefined, { origin: 'https://untrusted.example' })).status, 403);
    assert.equal((await request('POST', '/api/hooks/start', {})).status, 404);
    record('browser Origin guard and removed unauthenticated start endpoint');
    const firstTls = await tlsRequest();
    assert.equal(firstTls.status, 401);
    assert.match(firstTls.fingerprint, /^[a-f0-9]{64}$/);
    const settings = await invoke('mobileBridge', 'readMobileConnectionSettings');
    assert.equal(settings.mobileTlsPort, 19762);
    const pairedCode = await invoke('mobileBridge', 'startMobilePairing');
    const paired = await tlsRequest('POST', '/api/mobile/pair', { code: pairedCode.code, deviceName: 'Latest protocol QA' });
    assert.equal(paired.status, 200);assert.ok(paired.body.token);assert.equal(paired.fingerprint, firstTls.fingerprint);
    const auth = { authorization: `Bearer ${paired.body.token}` };
    assert.equal((await tlsRequest('GET', '/api/mobile/board', undefined, auth)).status, 200);
    record('actual RSA TLS listener, pairing and authenticated board over HTTPS');
    const project = await invoke('project', 'registerProject', 'Latest fixture', repo);assert.equal(project.success, true);
    const context = await invoke('kanban', 'createTask', { title: 'CLI context', branchName: 'qa-context', baseBranch: 'main', projectId: project.project.id, sessionType: 'terminal' });
    created.push(context.id);
    const targetsPath = path.join(context.worktreePath, '.kanvibe/targets.json');
    assert.equal(fs.statSync(targetsPath).mode & 0o777, 0o600);
    assert.ok(fs.existsSync(path.join(context.worktreePath, '.kanvibe/task.sh')));
    assert.equal((await request('POST', '/api/cli/tasks', { contextTaskId: context.id, branchName: 'forged', baseBranch: 'main' })).status, 401);
    const output = execFileSync('bash', ['.kanvibe/task.sh', 'create', '--branch', 'qa-child', '--title', 'Native CLI child', '--session-type', 'terminal'], { cwd: context.worktreePath, encoding: 'utf8', timeout: 90000 });
    assert.ok(output.includes('qa-child'), output);
    const all = await invoke('kanban', 'getTasksByStatus');
    const child = Object.values(all.tasks).flat().find(task => task.branchName === 'qa-child');assert.ok(child);created.push(child.id);
    record('installed task.sh creates a real worktree through authenticated CLI; targets permissions');
    fs.writeFileSync(path.join(child.worktreePath, 'dirty.txt'), 'dirty\n');
    let refused;
    try { execFileSync('bash', ['.kanvibe/task.sh', 'delete', '--yes', '--branch', 'qa-child'], { cwd: context.worktreePath, encoding: 'utf8', timeout: 90000, stdio: 'pipe' }); } catch (error) { refused = error; }
    assert.ok(refused, 'Dirty deletion must fail');assert.ok(await invoke('kanban', 'getTaskById', child.id));
    execFileSync('bash', ['.kanvibe/task.sh', 'delete', '--yes', '--branch', 'qa-child', '--force'], { cwd: context.worktreePath, encoding: 'utf8', timeout: 90000 });
    assert.equal(await invoke('kanban', 'getTaskById', child.id), null);
    record('CLI dirty worktree is preserved until explicit force deletion');
    const connected = await invoke('kanban', 'connectTerminalSession', context.id, 'terminal');
    const tabs = await invoke('terminalTabs', 'listTerminalTabs', context.id);
    const opened = await page.evaluate(({ taskId, tabId }) => window.kanvibeDesktop.openTerminal(taskId, tabId, 80, 24), { taskId: context.id, tabId: tabs.tabs[0].id });
    assert.equal(opened.ok, true);
    const same = await invoke('kanban', 'changeTaskSessionType', context.id, 'terminal', false);
    assert.equal(same.sessionName, connected.sessionName);
    assert.equal(await invoke('kanban', 'isTaskSessionAlive', context.id), false);
    const targets = await invoke('kanban', 'getSessionTypeChangeTargets', 'terminal');assert.equal(targets.taskCount, 0);
    record('same session type is a no-op and bulk target list excludes it');
    const ws = new WebSocket('ws://127.0.0.1:19752/api/mobile/events', { headers: auth });sockets.push(ws);
    const messages = [];
    ws.addEventListener('message', event => messages.push(JSON.parse(String(event.data))));
    await new Promise((resolve, reject) => { ws.addEventListener('open', resolve, { once: true });ws.addEventListener('error', reject, { once: true }); });
    const until = async predicate => { for (let i = 0; i < 200; i++) { const found = messages.find(predicate);if (found) return found;await pause(100); }throw new Error(`Missing event: ${JSON.stringify(messages)}`); };
    const connectedEvent = await until(message => message.type === 'connected');
    assert.ok(connectedEvent.commands.includes('delete-task'));
    ws.send(JSON.stringify({ type: 'command', requestId: 'missing', command: 'delete-task', taskId: 'missing' }));
    const missing = await until(message => message.requestId === 'missing');assert.equal(missing.ok, false);assert.equal(missing.code, 'task-not-found');
    ws.send(JSON.stringify({ type: 'command', requestId: 'invalid', command: 'delete-task', taskId: context.id, isForced: 'yes' }));
    assert.equal((await until(message => message.requestId === 'invalid')).code, 'invalid-command');
    const surfaces = await request('GET', `/api/mobile/tasks/${context.id}/surfaces`, undefined, auth);assert.equal(surfaces.status, 200);
    const paneId = surfaces.body.surfaces.tabs[0].panes[0].id;
    ws.send(JSON.stringify({ type: 'command', requestId: 'close-info', command: 'get-tab-close-info', taskId: context.id, paneId }));
    const closeInfo = await until(message => message.requestId === 'close-info');assert.equal(closeInfo.ok, true);assert.ok(Array.isArray(closeInfo.processNames));
    ws.send(JSON.stringify({ type: 'command', requestId: 'last-tab', command: 'close-tab', taskId: context.id, paneId }));
    const last = await until(message => message.requestId === 'last-tab');assert.equal(last.ok, false);assert.equal(last.code, 'last-tab');
    const added = await invoke('terminalTabs', 'createTerminalTab', context.id);assert.equal(added.ok, true);
    ws.send(JSON.stringify({ type: 'command', requestId: 'close-existing', command: 'close-tab', taskId: context.id, paneId }));
    const closed = await until(message => message.requestId === 'close-existing');assert.equal(closed.ok, true, JSON.stringify(closed));
    assert.ok(!closed.surfaces.tabs.some(tab => tab.panes.some(pane => pane.id === paneId)));
    record('mobile WebSocket command correlation, validation, close-info, actual close and last-tab guard');
    await invoke('kanban', 'changeTaskSessionType', context.id, 'herdr', true);
    await until(message => message.type === 'task-session-changed' && message.taskId === context.id);
    assert.equal((await invoke('kanban', 'getTaskById', context.id)).sessionType, 'herdr');
    const changedSurfaces = await request('GET', `/api/mobile/tasks/${context.id}/surfaces`, undefined, auth);
    assert.equal(changedSurfaces.status, 200, JSON.stringify(changedSurfaces));
    assert.equal(changedSurfaces.body.surfaces.sessionType, 'herdr');
    assert.equal(await invoke('kanban', 'isTaskSessionAlive', context.id), true);
    record('session conversion persists and broadcasts to mobile clients');
    const metadata = JSON.parse(fs.readFileSync(path.join(context.worktreePath, '.kanvibe/task.json'), 'utf8'));
    assert.equal(metadata.session.sessionType, 'herdr');
    const bulk = await invoke('kanban', 'createTask', { title: 'Bulk fixture', branchName: 'qa-bulk', baseBranch: 'main', projectId: project.project.id, sessionType: 'terminal' });created.push(bulk.id);
    assert.equal((await invoke('kanban', 'getSessionTypeChangeTargets', 'herdr')).taskCount, 2);
    fs.writeFileSync(path.join(bulk.worktreePath, '.claude/settings.json'), '{malformed');
    const changed = await invoke('kanban', 'changeAllTaskSessionTypes', 'herdr', false);
    assert.deepEqual(changed, { changedCount: 2, failedCount: 0 });
    assert.equal((await invoke('kanban', 'getTaskById', bulk.id)).sessionType, 'herdr');
    assert.equal((await invoke('kanban', 'getTaskById', context.id)).sessionName, metadata.session.sessionName);
    record('bulk conversion tolerates hook errors and preserves existing same-kind sessions');
    ws.close();
    await app.close();
    ({ app, page } = await launchKanVibeTauri({ appDataDir, hookPort: 19752 }));
    const nextTls = await tlsRequest();assert.equal(nextTls.fingerprint, firstTls.fingerprint);
    assert.equal((await invoke('kanban', 'getTaskById', context.id)).sessionType, 'herdr');
    record('TLS identity and converted session metadata survive native restart');
    for (const id of created) if (await invoke('kanban', 'getTaskById', id)) await invoke('kanban', 'deleteTask', id);
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ ok: true, checks }, null, 2));
  } catch (error) {
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ ok: false, checks, error: error.stack }, null, 2));throw error;
  } finally {
    for (const socket of sockets) socket.close();
    for (const id of created) await invoke('kanban', 'deleteTask', id, true).catch(() => {});
    fs.writeFileSync(path.join(out, 'runtime.log'), app.output());await app.close();
  }
}
main().catch(error => { console.error(error);process.exitCode = 1; });
